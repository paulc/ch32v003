//! Minimal async SSD1306 terminal driver.
//!
//! No framebuffer: characters are written straight out over I2C using page
//! addressing mode. Uppercase-only 5x7 font, ASCII 0x20..=0x5F.

use embedded_hal_async::i2c::I2c;

const CMD: u8 = 0x00;
const DATA: u8 = 0x40;
const CHAR_W: u8 = 6; // 5 font columns + 1 spacer

pub const COLS: u8 = 128 / CHAR_W; // 21 characters per row

#[derive(Clone, Copy)]
pub enum Size {
    S128x64,
    S128x32,
}

impl Size {
    fn mux(self) -> u8 {
        match self {
            Size::S128x64 => 0x3F,
            Size::S128x32 => 0x1F,
        }
    }
    fn com_pins(self) -> u8 {
        match self {
            Size::S128x64 => 0x12,
            Size::S128x32 => 0x02,
        }
    }
    pub fn rows(self) -> u8 {
        match self {
            Size::S128x64 => 8,
            Size::S128x32 => 4,
        }
    }
}

#[derive(Clone, Copy)]
pub enum Rotation {
    Deg0,
    Deg180,
}

pub struct Ssd1306<I> {
    i2c: I,
    addr: u8,
    size: Size,
}

impl<I: I2c> Ssd1306<I> {
    /// `addr` is usually 0x3C.
    pub fn new(i2c: I, addr: u8, size: Size) -> Self {
        Self { i2c, addr, size }
    }

    async fn cmds(&mut self, c: &[u8]) -> Result<(), I::Error> {
        let mut buf = [0_u8; 8];
        buf[0] = CMD;
        let n = c.len().min(7);
        buf[1..1 + n].copy_from_slice(&c[..n]);
        self.i2c.write(self.addr, &buf[..1 + n]).await
    }

    pub async fn init(&mut self, rot: Rotation) -> Result<(), I::Error> {
        self.cmds(&[0xAE]).await?; // display off
        self.cmds(&[0xD5, 0x80]).await?; // clock divide
        self.cmds(&[0xA8, self.size.mux()]).await?; // multiplex ratio
        self.cmds(&[0xD3, 0x00]).await?; // display offset
        self.cmds(&[0x40]).await?; // start line 0
        self.cmds(&[0x8D, 0x14]).await?; // charge pump on
        self.cmds(&[0x20, 0x02]).await?; // page addressing mode
        self.cmds(&[0xDA, self.size.com_pins()]).await?;
        self.cmds(&[0x81, 0x8F]).await?; // contrast
        self.cmds(&[0xD9, 0xF1]).await?; // precharge
        self.cmds(&[0xDB, 0x40]).await?; // vcomh
        self.cmds(&[0xA4, 0xA6]).await?; // resume from RAM, not inverted

        match rot {
            Rotation::Deg0 => self.cmds(&[0xA1, 0xC8]).await?,
            Rotation::Deg180 => self.cmds(&[0xA0, 0xC0]).await?,
        }

        self.cmds(&[0xAF]).await // display on
    }

    /// Move to a character cell. `col` is 0..COLS, `row` is 0..size.rows().
    pub async fn set_position(&mut self, col: u8, row: u8) -> Result<(), I::Error> {
        let x = col * CHAR_W;
        self.cmds(&[0xB0 | (row & 0x07), x & 0x0F, 0x10 | (x >> 4)])
            .await
    }

    pub async fn clear(&mut self) -> Result<(), I::Error> {
        let mut blank = [0u8; 33]; // control byte + 32 blank columns
        blank[0] = DATA;
        for row in 0..self.size.rows() {
            self.set_position(0, row).await?;
            for _ in 0..4 {
                self.i2c.write(self.addr, &blank).await?;
            }
        }
        self.set_position(0, 0).await
    }

    pub async fn write_char(&mut self, c: char) -> Result<(), I::Error> {
        let mut buf = [0u8; 7];
        buf[0] = DATA;
        buf[1..6].copy_from_slice(&glyph(c));
        // buf[6] stays 0: the inter-character spacer column
        buf[6] = 0;
        self.i2c.write(self.addr, &buf).await
    }

    pub async fn write_str(&mut self, s: &str) -> Result<(), I::Error> {
        for c in s.bytes() {
            self.write_char(c as char).await?;
        }
        Ok(())
    }

    /// Write a whole row, clearing whatever was there before.
    pub async fn write_line(&mut self, row: u8, s: &str) -> Result<(), I::Error> {
        self.set_position(0, row).await?;
        let mut n = 0u8;
        for c in s.bytes().take(COLS as usize) {
            self.write_char(c as char).await?;
            n += 1;
        }
        while n < COLS {
            self.write_char(' ').await?;
            n += 1;
        }
        Ok(())
    }
}

/// 5x7 font, ASCII 0x20..=0x5F. Lowercase folds to uppercase; anything else
/// renders as a space. Column-major, bit 0 = top row.
fn glyph(c: char) -> [u8; 5] {
    let b = c as u32;
    let b = if (0x61..=0x7A).contains(&b) {
        b - 0x20
    } else {
        b
    };
    if !(0x20..=0x5F).contains(&b) {
        return [0; 5];
    }
    let i = (b - 0x20) as usize * 5;
    [FONT[i], FONT[i + 1], FONT[i + 2], FONT[i + 3], FONT[i + 4]]
}

